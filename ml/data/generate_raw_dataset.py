"""GENERATES SYNTHETIC / DEMO cold-chain telemetry for ML development.

This is NOT real-world data: shipments are simulated (sensor random walk,
door events, GPS routes, cooling failures). It exists only to develop and
test the ML pipeline. Real validation requires real sensor data.
Writes: data/raw/coldchain_synthetic_v1.csv + data/raw/README.md notice.
"""
import argparse
from pathlib import Path

import numpy as np
import pandas as pd

ROOT = Path(__file__).resolve().parents[2]
GAP = 15  # minutes between readings

# name, category, min_t, max_t, shelf_life_h, q10, exc_limit_min, hum_lo, hum_hi
PRODUCTS = [
    ("Fresh Milk", "dairy", 2.0, 6.0, 48.0, 2.5, 30.0, 40, 70),
    ("Greek Yogurt", "dairy", 2.0, 8.0, 72.0, 2.5, 45.0, 40, 70),
    ("Frozen Peas", "frozen", -22.0, -18.0, 500.0, 2.0, 60.0, 30, 60),
    ("Leafy Greens", "produce", 2.0, 8.0, 96.0, 2.8, 40.0, 85, 98),
    ("Fresh Salmon", "seafood", 0.0, 4.0, 36.0, 3.0, 20.0, 70, 95),
    ("Vaccines", "pharma", 2.0, 8.0, 720.0, 2.0, 15.0, 35, 65),
]
CITIES = [("Bengaluru", 12.97, 77.59), ("Chennai", 13.08, 80.27),
          ("Hyderabad", 17.38, 78.48), ("Mumbai", 19.07, 72.87),
          ("Pune", 18.52, 73.86), ("Kochi", 9.93, 76.26)]


def km(a, b):
    p1, p2 = np.radians(a[1]), np.radians(b[1])
    dp, dl = np.radians(b[1] - a[1]), np.radians(b[2] - a[2])
    h = np.sin(dp / 2) ** 2 + np.cos(p1) * np.cos(p2) * np.sin(dl / 2) ** 2
    return 2 * 6371.0 * np.arcsin(np.sqrt(h))


def shipment_rows(rng, sid, start, n, spoil):
    name, cat, lo, hi, shelf, q10, lim, hlo, hhi = PRODUCTS[rng.integers(len(PRODUCTS))]
    a = CITIES[rng.integers(len(CITIES))]
    b = CITIES[rng.integers(len(CITIES))]
    while b is a:
        b = CITIES[rng.integers(len(CITIES))]
    base = rng.uniform(lo + 0.15 * (hi - lo), lo + 0.85 * (hi - lo))
    direction = 1.0 if rng.random() < 0.7 else -1.0  # warm excursion vs under-cooling
    fail_at = int(rng.uniform(0.4, 0.8) * n) if spoil else None
    cur, temps, doors = base, [], []
    for i in range(n):
        cur += rng.normal(0, 0.08) + (base - cur) * 0.05  # AR(1) around setpoint
        door = int(rng.random() < 0.05)
        if door:
            cur += direction * rng.uniform(0.4, 1.6)
        if fail_at is not None and i >= fail_at:
            cur += direction * rng.uniform(0.10, 0.55)  # cooling failure
        temps.append(round(float(np.clip(cur, -30.0, 45.0)), 3))
        doors.append(door)
    lats = np.linspace(a[1], b[1], n) + rng.normal(0, 0.01, n)
    lons = np.linspace(a[2], b[2], n) + rng.normal(0, 0.01, n)
    hum = np.clip(np.linspace(hlo, hhi, n) + rng.normal(0, 2.0, n), 0, 100)
    batt = np.linspace(100.0, 72.0, n)
    ts = pd.date_range(start, periods=n, freq=f"{GAP}min")
